const assert = require('node:assert/strict');
const root = process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES;
const { chromium } = root ? require(root + '/playwright') : require('playwright');
const base = process.argv[2] || 'http://127.0.0.1:8766/';
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '?porciones=3');
    await page.waitForFunction(() => document.getElementById('exportar').getAttribute('aria-disabled') === 'false');
    assert.equal(await page.locator('#porciones').inputValue(), '3');
    const row = name => page.locator('#lista tr').filter({ hasText: name });
    assert.match(await row('Philadelphia').textContent(), /52\.5 g1 tarrina/);
    assert.match(await row('Cebolla fresca').textContent(), /352\.5 g360 g/);
    assert.match(await row('Aceite de oliva').textContent(), /180 mlDespensa/);
    assert.match(await page.locator('#exportar').getAttribute('href'), /exports%2F3\.json/);
    await page.locator('#menos').click();
    assert.equal(await page.locator('#porciones').inputValue(), '2');
    assert.match(await row('Philadelphia').textContent(), /35 g1 tarrina/);
    await page.locator('#mas').click();
    assert.equal(await page.locator('#porciones').inputValue(), '3');
    await page.locator('#porciones').fill('15');
    assert.match(await row('Philadelphia').textContent(), /262\.5 g2 tarrinas/);
    const link = await page.locator('#exportar').getAttribute('href');
    const query = new URL(link).searchParams;
    assert.equal(query.get('baseQuantity'), '15');
    assert.equal(query.get('requestedQuantity'), '15');
    const local = await page.request.get(base + 'exports/15.json');
    const payload = await local.json();
    assert.equal(payload.yield, '15');
    assert.equal(payload.items.find(x => x.itemId.includes('Philadelphia')).spec, '2 tarrinas');
    await page.locator('#porciones').fill('1.5');
    assert.equal(await page.locator('#exportar').getAttribute('aria-disabled'), 'true');
    assert.equal(await page.locator('#exportar').getAttribute('href'), null);
    await page.locator('#porciones').fill('1');
    assert.equal(await page.locator('#menos').isDisabled(), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.setViewportSize({ width: 1024, height: 768 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    assert.deepEqual(errors, []);
    const fail = await browser.newPage();
    await fail.route('**/vista.json', route => route.abort());
    await fail.goto(base);
    await fail.waitForFunction(() => document.getElementById('porciones').disabled);
    assert.equal(await fail.locator('#exportar').getAttribute('href'), null);
    console.log('Selector, enlaces, porciones/JSON, redondeo final, vista móvil/tablet y fallo de carga: OK');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
